export function curriculumForDay(day: number): CurriculumDay | undefined {
  return BUILD_CURRICULUM.find((d) => d.day === day);
}

export function curriculumDayForProgramStart(startIso: string): number {
  const start = new Date(startIso).getTime();
  if (Number.isNaN(start)) return 0;
  const diff = Math.floor((Date.now() - start) / 86400000);
  return Math.max(0, Math.min(15, diff));
}
